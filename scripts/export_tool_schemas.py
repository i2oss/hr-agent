"""Write docs/tool-schemas.json from the live list_tools() of both MCP servers (SPEC slice 4, step 7).

Usage: uv run python scripts/export_tool_schemas.py           # write
       uv run python scripts/export_tool_schemas.py --check   # CI: fail if the committed file is stale
"""

from __future__ import annotations

import asyncio
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from mcp import Client  # noqa: E402

from app.agent.mcp_client import strip_injected  # noqa: E402
from app.config import Settings  # noqa: E402
from mcp_servers.hr.server import build_hr_server  # noqa: E402
from mcp_servers.hr.store import MockActionStore  # noqa: E402
from mcp_servers.policy.retrieval import PolicyIndex  # noqa: E402
from mcp_servers.policy.server import build_policy_server  # noqa: E402

OUT = ROOT / "docs" / "tool-schemas.json"


class _NoEmbedder:
    """list_tools() never embeds anything, so the export doesn't load the model."""

    model_name = "none"

    def embed_query(self, text: str) -> Any:
        raise NotImplementedError


async def export() -> dict[str, Any]:
    settings = Settings(_env_file=None)  # type: ignore[call-arg]
    servers = {
        "policy": build_policy_server(PolicyIndex.load(settings.index_path, _NoEmbedder()), settings),  # type: ignore[arg-type]
        "hr": build_hr_server(settings, MockActionStore()),
    }
    out: dict[str, Any] = {"_note": "Generated by scripts/export_tool_schemas.py from live list_tools(). "
                                    "model_input_schema is what the LLM sees (loop-injected arguments removed).",
                           "servers": {}}
    for name, server in servers.items():
        async with Client(server) as c:
            tools = (await c.list_tools()).tools
        out["servers"][name] = [
            {
                "name": t.name,
                "description": t.description,
                "annotations": t.annotations.model_dump(exclude_none=True, by_alias=True) if t.annotations else {},
                "input_schema": t.input_schema,
                "model_input_schema": strip_injected(t.input_schema)[0],
                "output_schema": t.output_schema,
            }
            for t in sorted(tools, key=lambda t: t.name)
        ]
    return out


def main() -> int:
    text = json.dumps(asyncio.run(export()), indent=2, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("docs/tool-schemas.json is stale: run `make schemas`")
            return 1
        print("OK: docs/tool-schemas.json is current")
        return 0
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(text)
    n = sum(len(v) for v in json.loads(text)["servers"].values())
    print(f"wrote {OUT.relative_to(ROOT)} ({n} tools)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
